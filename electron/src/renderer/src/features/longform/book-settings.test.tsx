import { fireEvent, render, screen, waitFor } from '@testing-library/react';
import { expect, it, vi } from 'vitest';
import '@/i18n';
import type { Draft } from './longform-session';
import { BookSettings } from './book-settings';

vi.mock('@/lib/api/client', () => ({
  apiJson: vi.fn(async () => ({ path: '/saved/cover.png' })),
  describeError: (error: unknown) => String(error),
}));

const draft = (cover: Draft['cover'] = null): Draft =>
  ({ metadata: {}, loudness: 'off', cover, lexicon: [] }) as unknown as Draft;

it('renders an imported cover filename as text, never as markup', () => {
  const filename = '<img src=x onerror=alert(1)>.png';
  const { container } = render(
    <BookSettings
      draft={draft({ path: '/saved/cover.png', name: filename })}
      disabled={false}
      pronunciation={false}
      onChange={vi.fn()}
      onBusy={vi.fn()}
    />,
  );

  expect(screen.getByText(filename)).toBeInTheDocument();
  expect(container.querySelector('img')).toBeNull();
});

it('previews only the browser-created object URL after a successful upload', async () => {
  const objectUrl = 'blob:app://voicestudio/cover-preview';
  const create = vi.spyOn(URL, 'createObjectURL').mockReturnValue(objectUrl);
  const revoke = vi.spyOn(URL, 'revokeObjectURL').mockImplementation(() => {});
  const onChange = vi.fn();
  const { container, rerender, unmount } = render(
    <BookSettings
      draft={draft()}
      disabled={false}
      pronunciation={false}
      onChange={onChange}
      onBusy={vi.fn()}
    />,
  );
  const file = new File(['<script>alert(1)</script>'], 'cover.png', { type: 'text/html' });
  fireEvent.change(container.querySelector('input[type="file"]')!, {
    target: { files: [file] },
  });
  await waitFor(() =>
    expect(onChange).toHaveBeenCalledWith({
      cover: { path: '/saved/cover.png', name: 'cover.png' },
    }),
  );
  rerender(
    <BookSettings
      draft={draft({ path: '/saved/cover.png', name: 'cover.png' })}
      disabled={false}
      pronunciation={false}
      onChange={onChange}
      onBusy={vi.fn()}
    />,
  );
  // The preview source is generated by the browser, never the file contents,
  // filename, or backend path. React gives it to an image element as a URL.
  expect(create).toHaveBeenCalledWith(file);
  expect(container.querySelector('img')?.getAttribute('src')).toBe(objectUrl);
  expect(container.querySelector('script')).toBeNull();
  unmount();
  expect(revoke).toHaveBeenCalledWith(objectUrl);
  create.mockRestore();
  revoke.mockRestore();
});
